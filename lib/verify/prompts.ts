/**
 * 시트 `getFormatGuide`(K열 answer_type 기반, `Itemverification.gs:522-528`)의 4갈래를
 * Mathory 재료로 재현한다 — Mathory에는 answer_type 열이 없으므로 블록 구성과 answer로 정한다.
 */
export function deriveAnswerFormat(a: {
  hasChoices: boolean;
  hasGanaOrRoman: boolean;
  answer: string;
}): string {
  if (a.hasChoices && a.hasGanaOrRoman) return "옳은 선택지 조합 (예: 'ㄱ' 또는 'ㄱ, ㄴ' 등)";
  if (a.hasChoices) return '선택지 번호 하나 (① ~ ⑤)';
  if (/^\d{1,3}$/.test(String(a.answer ?? '').trim())) return '1~999 사이의 자연수';
  return '표준 수치 형식';
}

