/** 2차 user 프롬프트의 {candidates} 자리에 넣을 가독 텍스트 (시트 `formatCandidatesForJudge_` 등가) */
export function formatCandidatesForJudge(
  cands: { id: string; tag: string; quote: string; reason: string }[],
): string {
  return cands
    .map((c) => `${c.id} [${c.tag}]\n지점: ${c.quote}\n주장: ${c.reason}`)
    .join('\n\n');
}
