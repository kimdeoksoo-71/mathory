/**
 * `{key}` 치환.
 *
 * ⚠️ **반드시 함수형 콜백을 쓸 것.** `String.replace`에 치환값을 *문자열로* 넘기면
 *    값 안의 `$$`·`$&`·`` $` ``가 치환 패턴으로 해석되어 LaTeX가 손상된다.
 *    콜백 반환값은 그 해석을 받지 않는다.
 *    (시트 STEP3가 같은 이유로 함수형을 쓴다 — `QualityVerification.gs:271-273`의 `★` 주석.
 *     반면 STEP1은 아직 `.replace('{problem}', stem)`(`Itemverification.gs:302-303`)이다 —
 *     고쳐지지 않은 자리이니 그쪽을 베끼지 말 것.)
 */
export function fillTemplate(tpl: string, vars: Record<string, string>): string {
  return String(tpl ?? '').replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? vars[k] : m));
}

