export interface LabeledBlock {
  blockKey: string;
  type: string;
  text: string;
}

/**
 * 블록마다 `[블록 n]` 라벨을 붙여 한 덩어리로.
 * 라벨은 모델이 위치를 가리키게 하는 **힌트일 뿐**이다 — 실제 앵커는
 * `anchorByQuote`가 인용 실재성으로 확정한다(모델의 자기 신고를 믿지 않는다).
 */
export function labelBlocks(blocks: LabeledBlock[]): string {
  return blocks
    .map((b, i) => `[블록 ${i + 1}]${b.type && b.type !== 'text' ? ` (${b.type})` : ''}\n${b.text}`)
    .join('\n\n');
}

/** 대상 블록 텍스트 총량 (사전 차단·상한 판정용) */
export function totalChars(blocks: LabeledBlock[]): number {
  return blocks.reduce((n, b) => n + (b.text ? b.text.length : 0), 0);
}

